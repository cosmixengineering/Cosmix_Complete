using System.Text.Json;
using Cosmix.Application.Attendance.Common;
using Cosmix.Application.Attendance.Shifts;
using Cosmix.Application.Authentication;
using Cosmix.Application.Common.BackgroundJobs;
using Cosmix.Application.Common.Files;
using Cosmix.Application.Common.Notifications;
using Cosmix.Domain.Authentication;
using Cosmix.Domain.Common.Files;
using Cosmix.Domain.Common.Jobs;
using Cosmix.Domain.Common.Reports;

namespace Cosmix.Application.Attendance.Reports;

public sealed class AttendanceReportHandler(IAttendanceReportRepository reports, AttendanceReportService service,
    ISchedulingJournalRepository sessions, IPrivateFileStore files, INotificationOutbox notifications, TimeProvider clock)
    : IDurableJobHandler
{
    public string MessageType => AttendanceReportService.MessageType;

    public async Task ApplyAsync(OutboxMessage message, CancellationToken ct)
    {
        if (!Guid.TryParseExact(message.DeduplicationKey, "N", out var jobId))
            throw new DurableJobFailure("invalid_report_job_binding", false);
        await reports.LockAuthorizationAsync(ct);
        var job = await reports.FindWorkerAsync(jobId, ct);
        if (job is null || job.ProtectedFilterScopeReference != message.EncryptedPayloadReference || job.State != ReportJobState.Pending)
            throw new DurableJobFailure("invalid_report_job_binding", false);
        var scope = await service.ScopeAsync(job, ct);
        if (scope.Requester.Client != SessionClient.Web || !scope.Requester.MfaSatisfied ||
            !await sessions.IsCurrentSessionAsync(scope.Requester, ct))
            throw new DurableJobFailure("report_requester_session_unavailable", false);
        try { await service.RequireScopeAsync(scope.Requester, scope, ct); }
        catch (AuthenticationFailure error) when (error.StatusCode == 403)
        { throw new DurableJobFailure("report_scope_revoked", false); }

        // Start is deliberately not saved separately: an interrupted outbox transaction restores Pending.
        job.Start();
        var rows = await service.LoadRowsAsync(scope.EmployeeIds, scope.From, scope.To, ct);
        var now = clock.GetUtcNow();
        var metadata = FactualAttendanceDocument.Metadata(job.Id, now, scope, rows);
        var bytes = FactualAttendanceDocument.Generate(job.Format, rows, metadata);
        if (bytes.Length > 2_000_000) throw new DurableJobFailure("report_output_limit", false);
        var reference = await files.WriteAsync(bytes, AttendanceReportService.FilePurpose(job.Id, job.Format), ct);
        var extension = FactualAttendanceDocument.Extension(job.Format);
        var stored = new StoredFile(reference.StorageKey, $"attendance-factual-{job.Id:N}{extension}", extension, FactualAttendanceDocument.ContentType(job.Format),
            reference.SizeBytes, reference.Sha256, job.RequestedByUserId, now, reference.KeyReference);
        // These are controlled server-generated bytes, not user uploads. Do not fabricate malware scan results.
        reports.Add(stored);
        var output = new AttendanceReportOutput(new(reference.StorageKey, reference.ObjectVersion, reference.Sha256,
            reference.KeyReference, reference.SizeBytes), stored.Id, rows, FactualAttendanceDocument.Version(job.Format), job.Format, metadata);
        var manifest = await files.WriteAsync(JsonSerializer.SerializeToUtf8Bytes(output), AttendanceReportService.OutputPurpose(job.Id), ct);
        // The one-hour authenticated download window is not a retention/deletion policy.
        job.Complete(stored.Id, AttendanceOperation.Reference(manifest), now, now.AddHours(1));
        await notifications.StageAsync(new(job.Id, scope.Requester.AccountId, NotificationTemplates.ReportReady, job.Id),
            new AuthRequestContext("", message.CorrelationId), ct);
        // Outbox completion, job, StoredFile, ready-notification intent and audit share the final save.
    }
}
